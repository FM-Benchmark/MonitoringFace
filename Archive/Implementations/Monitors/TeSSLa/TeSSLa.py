# Output contract of specs generated by TeSSLaPolicyConverter.
# Phase 0 (past-only): "<tp>: mf_v = <bool>".
# Phase 1 (open past formulas): additionally "0: mf_cols = x1,x2" once,
# "<tp>: mf_ts = <ts>" per timepoint, and "<tp>: mf_set = Set(List(..), ..)"
# exactly at satisfying timepoints (the JVM prints large sets as HashSet).
# Phase 2 (bounded-future root): "<j>: mf_late_set = Set(List(tp, cols..))"
# at the closing timepoint j, each element tagged with the timepoint it
# belongs to; mf_cols (open roots only) and mf_ts as in phase 1; no mf_v.
_VERDICT_RE = re.compile(r"^\s*(\d+)\s*:\s*mf_v\s*=\s*(true|false)\s*$")
_COLS_RE = re.compile(r"^\s*\d+\s*:\s*mf_cols\s*=\s*(.+?)\s*$")
_TS_RE = re.compile(r"^\s*(\d+)\s*:\s*mf_ts\s*=\s*(-?\d+)\s*$")
_SET_RE = re.compile(r"^\s*(\d+)\s*:\s*mf_set\s*=\s*(?:Hash)?Set\((.*)\)\s*$")
_LATE_RE = re.compile(r"^\s*\d+\s*:\s*mf_late_set\s*=\s*(?:Hash)?Set\((.*)\)\s*$")
_LIST_RE = re.compile(r"List\(([^)]*)\)")


class TeSSLa(BaseMonitorTemplate, OfflineRunnable):
    def __init__(self, image: AnyStr, name: str, params: AnyStr):
        super().__init__(image, name, params)

    def preprocessing_data(
            self, path_to_folder: AnyStr, data_file: AnyStr,
            trace_source: InputOutputTraceFormats, path_manager: PathManager
    ):
        self.params[TRACE_KEY] = data_file.removeprefix("data/")

    def preprocessing_policy(
            self, path_to_folder: AnyStr, policy_file: AnyStr, signature_file: AnyStr,
            policy_source: InputOutputPolicyFormats, path_manager: PathManager
    ):
        self.params[FOLDER_KEY] = path_to_folder
        self.params[POLICY_KEY] = policy_file.removeprefix("data/")

    def construct_offline_command(self, time_on=None, time_out=None) -> Tuple[List[str], Optional[str]]:
        # NOTE: experiments must set no_measure: True. The TeSSLa image keeps
        # ENTRYPOINT ["tessla"] (with its own /usr/bin/time wrapper writing
        # scratch/stats.txt), so the framework's measure path, which wraps the
        # command in /bin/sh -c, would hand "/bin/sh" to the tessla launcher
        # as its spec argument and fail with a confusing CLI error.
        #
        # The data folder itself is the container mount (WORKDIR=/data), so paths must be
        # relative to it. Strip any leading "data/" here so this holds whether the framework
        # took the auto-conversion (distance 0) path or the custom preprocessing path.
        policy = str(self.params[POLICY_KEY]).removeprefix("data/")
        trace = str(self.params[TRACE_KEY]).removeprefix("data/")
        # -r: without it the interpreter silently drops events on undeclared
        # streams, so a stream-naming mismatch would look like an empty verdict.
        # Only applied to policies produced by the auto-conversion chain (they
        # land under scratch/); a hand-written case-study spec may deliberately
        # ignore streams, and its behavior must not change.  Overridable both
        # ways via params: no_reject_undeclared / reject_undeclared: True.
        converted = str(self.params.get(POLICY_KEY, "")).startswith("scratch/")
        reject = (converted or self.params.get("reject_undeclared")) and not self.params.get("no_reject_undeclared")
        flags = ["--reject-undeclared-inputs"] if reject else []
        cmd = flags + [policy, trace]
        return cmd, "interpreter"

    def post_processing_offline(self, stdout_input: AnyStr) -> AbstractOutputStructure:
        # The interpreter exits 0 on runtime-phase errors (including trace
        # format violations); only stderr betrays them.
        lines = (stdout_input or "").splitlines()
        for line in lines:
            if line.startswith("Runtime error:") or line.startswith("Compilation failed"):
                raise ToolException(f"TeSSLa: {line.strip()}")

        columns = None
        tp_to_ts = {}
        set_lines = []
        late_bodies = []
        for line in lines:
            cols_match = _COLS_RE.match(line)
            if cols_match:
                columns = [c.strip() for c in cols_match.group(1).split(",") if c.strip()]
                continue
            ts_match = _TS_RE.match(line)
            if ts_match:
                tp_to_ts[int(ts_match.group(1))] = int(ts_match.group(2))
                continue
            set_match = _SET_RE.match(line)
            if set_match:
                set_lines.append(set_match)
                continue
            late_match = _LATE_RE.match(line)
            if late_match:
                late_bodies.append(late_match.group(1))

        if late_bodies:
            # Phase-2 bounded-future verdicts: elements are tagged with the
            # timepoint they belong to; re-key by the tag.
            by_timepoint = {}
            for body in late_bodies:
                for list_match in _LIST_RE.finditer(body):
                    parts = [p.strip() for p in list_match.group(1).split(",")]
                    time_point = int(parts[0])
                    by_timepoint.setdefault(time_point, []).append(parts[1:])
            if columns:
                late_verdicts = OooVerdicts(VariableOrder(columns))
                for time_point in sorted(by_timepoint):
                    late_verdicts.insert(
                        by_timepoint[time_point], time_point,
                        tp_to_ts.get(time_point, time_point),
                    )
                return late_verdicts
            result = PropositionList(DefaultVariableOrder())
            for time_point in sorted(by_timepoint):
                result.insert(
                    Proposition(True), time_point,
                    tp_to_ts.get(time_point, time_point),
                )
            return result

        if columns:
            # Phase-1 valuation-set verdicts. Values stay STRINGS to match
            # parse_pattern's convention for the MonPoly-family oracles;
            # Assignment equality is by variable name, so the sorted column
            # order compares correctly against the oracle's own order.
            verdicts = Verdicts(VariableOrder(columns))
            for set_match in set_lines:
                time_point = int(set_match.group(1))
                assignments = []
                for list_match in _LIST_RE.finditer(set_match.group(2)):
                    inner = list_match.group(1).strip()
                    assignments.append(
                        [value.strip() for value in inner.split(",")] if inner else []
                    )
                if assignments:
                    verdicts.insert(
                        assignments, time_point, tp_to_ts.get(time_point, time_point)
                    )
            return verdicts

        # Phase-0 fallback: closed formulas and native srv case-study specs.
        result = PropositionList(DefaultVariableOrder())
        for line in lines:
            match = _VERDICT_RE.match(line)
            if match and match.group(2) == "true":
                result.insert(Proposition(True), int(match.group(1)))
        return result

    @staticmethod
    def supported_policy_formats() -> List[InputOutputPolicyFormats]:
        return [InputOutputPolicyFormats.SRV_POLICY]

    @staticmethod
    def supported_trace_formats() -> List[InputOutputTraceFormats]:
        return [InputOutputTraceFormats.SRV_TRACE]
